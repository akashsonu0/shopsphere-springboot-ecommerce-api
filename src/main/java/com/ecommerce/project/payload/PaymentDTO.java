package com.ecommerce.project.payload;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

@Data
@NoArgsConstructor
@AllArgsConstructor
@Schema(description = "Payment details associated with an order")
public class PaymentDTO {

    @Schema(
        description = "Unique ID of the payment record",
        example = "4001",
        accessMode = Schema.AccessMode.READ_ONLY
    )
    private Long paymentId;

    @Schema(
        description = "Payment method used by the customer",
        example = "UPI"
    )
    private String paymentMethod;

    @Schema(
        description = "Payment transaction ID generated by the payment gateway",
        example = "pay_123456789"
    )
    private String pgPaymentId;

    @Schema(
        description = "Current status of the payment",
        example = "SUCCESS"
    )
    private String pgStatus;

    @Schema(
        description = "Response message received from the payment gateway",
        example = "Payment completed successfully"
    )
    private String pgResponseMessage;

    @Schema(
        description = "Name of the payment gateway",
        example = "Razorpay"
    )
    private String pgName;
}