package com.ecommerce.project.payload;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

@Data
@NoArgsConstructor
@AllArgsConstructor
@Schema(description = "Request payload containing address and payment details for an order")
public class OrderRequestDTO {

    @Schema(
        description = "ID of the delivery address selected by the customer",
        example = "101"
    )
    private Long addressId;

    @Schema(
        description = "Payment method selected by the customer",
        example = "UPI"
    )
    private String paymentMethod;

    @Schema(
        description = "Name of the payment gateway",
        example = "Razorpay"
    )
    private String pgName;

    @Schema(
        description = "Payment ID generated by the payment gateway",
        example = "pay_123456789"
    )
    private String pgPaymentId;

    @Schema(
        description = "Status returned by the payment gateway",
        example = "SUCCESS"
    )
    private String pgStatus;

    @Schema(
        description = "Message returned by the payment gateway",
        example = "Payment completed successfully"
    )
    private String pgResponseMessage;
}